const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--host-resolver-rules=MAP dns.integration.example 127.0.0.1']});
 const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('https://dns.integration.example/');
 await page.getByLabel('Password',{exact:true}).fill('disposable-integration-password');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.locator('#workspace').waitFor({state:'visible'});
 await page.locator('#content [data-new-device]').click();
 await page.locator('#editor-form [name=name]').fill('Browser test phone');
 await page.locator('#editor-form [name=profile]').selectOption('adults');
 await page.locator('#editor-form [type=submit]').click();
 await page.locator('#editor').waitFor({state:'hidden'});
 await page.locator('.sidebar [data-view=devices]').click();
 await page.getByRole('heading',{name:'Browser test phone',exact:true}).waitFor();
 await page.locator('.sidebar [data-view=profiles]').click();
 const kids=page.locator('#content .card').filter({has:page.getByRole('heading',{name:'Kids',exact:true})});
 await kids.getByRole('button',{name:'Edit',exact:true}).click();
 await page.locator('#category-gambling').uncheck();
 await page.locator('#editor-form [type=submit]').click();await page.locator('#editor').waitFor({state:'hidden'});
 const state=await page.evaluate(()=>fetch('/api/console/state').then(r=>r.json()));
 assert.equal(state.profiles.kids.categories.includes('gambling'),false);
 await page.locator('.sidebar [data-view=overview]').click();
 await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.mobile-nav [data-view=devices]').click();
 await page.getByRole('heading',{name:'Browser test phone',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
 await page.locator('.mobile-nav [data-view=settings]').click();
 await page.getByRole('heading',{name:'Your password',exact:true}).waitFor();
 await page.locator('.top-actions [data-action=logout]').click();
 await page.locator('#login').waitFor({state:'visible'});
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: login, device creation, profile categories, desktop/mobile layout, settings and logout.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
